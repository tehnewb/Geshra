package geshra.net.web.ui.components.tree;

/**
 * Selects whether tree clicks permit no selection, one selected node, or multiple selected nodes.
 */
public enum TreeSelectionMode {

    /**
     * None selection or protocol value.
     */
    NONE,
    /**
     * Single selection or protocol value.
     */
    SINGLE,
    /**
     * Multiple selection or protocol value.
     */
    MULTIPLE

}
