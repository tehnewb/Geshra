package geshra.net.web.ui.components.table;

/**
 * Selects whether table interaction permits no selected rows, one row, or multiple rows.
 */
public enum TableSelectionMode {
    /**
     * None selection or protocol value.
     */
    NONE,
    /**
     * Multiple selection or protocol value.
     */
    MULTIPLE,
    /**
     * Single selection or protocol value.
     */
    SINGLE
}
