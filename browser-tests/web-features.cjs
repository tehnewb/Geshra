const assert = require('node:assert/strict');
const {chromium, firefox, webkit} = require('playwright');

(async () => {
    const engine = {chromium, firefox, webkit}[process.env.BROWSER || 'chromium'];
    const browser = await engine.launch({headless: true, executablePath: process.env.BROWSER_EXECUTABLE || undefined});
    const base = process.env.BASE_URL || 'http://localhost:4040';
    const context = await browser.newContext();
    const page = await context.newPage();
    page.setDefaultTimeout(10000);
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('console', message => {if (message.type() === 'error') errors.push(message.text());});
    await context.route('**/favicon.ico', route => route.fulfill({status: 204}));
    const cookie = async name => (await context.cookies()).find(value => value.name === name);
    try {
        const initial = await context.request.get(base + '/');
        assert.match(await initial.text(), /<title data-geshra-seo>Hello from Spring Boot/);
        assert.match(await initial.text(), /<a href="\/components">/);
        const crawler = await browser.newContext({javaScriptEnabled: false});
        const crawlPage = await crawler.newPage();
        await crawlPage.goto(base + '/');
        assert.equal(await crawlPage.getByRole('heading', {name: 'Hello from Spring Boot'}).count(), 1);
        await crawler.close();
        assert.equal((await context.request.get(base + '/account')).status(), 401);
        await page.goto(base + '/login');
        await page.getByLabel('Username', {exact: true}).waitFor();
        const anonymousCookie = await cookie('sessionID');
        assert.equal(anonymousCookie.httpOnly, true);
        assert.equal(anonymousCookie.sameSite, 'Lax');
        assert.equal(await page.evaluate(() => document.cookie.includes('sessionID=')), false);
        await page.getByLabel('Username', {exact: true}).fill('demo');
        await page.getByLabel('Password', {exact: true}).fill('wrong-password');
        await page.getByRole('button', {name: 'Sign in', exact: true}).click();
        await page.getByText('Username or password was not accepted', {exact: true}).waitFor();
        assert.equal((await cookie('sessionID')).value, anonymousCookie.value);
        await page.getByLabel('Password', {exact: true}).fill(process.env.DEMO_PASSWORD || 'browser-test-password');
        await page.getByRole('button', {name: 'Sign in', exact: true}).click();
        await page.getByRole('heading', {name: 'Welcome demo', exact: true}).waitFor();
        const authenticatedCookie = await cookie('sessionID');
        assert.notEqual(authenticatedCookie.value, anonymousCookie.value);
        assert.equal(authenticatedCookie.httpOnly, true);
        assert.equal((await context.request.get(base + '/account')).status(), 200);
        assert.equal(await page.locator('meta[name="robots"][content="noindex,nofollow"]').count(), 1);
        await page.getByText('Session visits: 1', {exact: true}).waitFor();
        const saved = page.waitForResponse(response => response.url().endsWith('/_geshra/cookies'));
        await page.getByRole('button', {name: 'Save private preference', exact: true}).click();
        await saved;
        assert.equal((await cookie('privatePreference')).httpOnly, true);
        assert.equal(await page.evaluate(() => document.cookie.includes('privatePreference=')), false);
        await page.getByRole('button', {name: 'Read preference', exact: true}).click();
        await page.getByText('Preference: dark', {exact: true}).waitFor();
        await page.reload();
        await page.getByText('Session visits: 2', {exact: true}).waitFor();
        assert.equal((await cookie('sessionID')).value, authenticatedCookie.value);
        const csrf = await page.evaluate(async () => (await window.geshra.session()).csrfToken);
        const denied = await context.request.post(base + '/_geshra/logout', {headers: {'X-CSRF-Token': 'wrong'}});
        assert.equal(denied.status(), 403);
        assert.ok(csrf.length >= 32);
        await page.getByRole('button', {name: 'Sign out', exact: true}).click();
        await page.getByRole('heading', {name: 'Hello from Spring Boot', exact: true}).waitFor();
        assert.notEqual((await cookie('sessionID')).value, authenticatedCookie.value);
        assert.equal((await context.request.get(base + '/account')).status(), 401);
        assert.equal(await page.locator('meta[name="robots"][content="noindex,nofollow"]').count(), 0);
        assert.equal(await page.title(), 'Hello from Spring Boot');
        assert.deepEqual(errors, []);
        console.log(JSON.stringify({passed: true, browser: process.env.BROWSER || 'chromium', seoWithoutJavaScript: true, httpOnlyCookies: true, loginRotation: true, logoutRotation: true, sessionResume: true}));
    } finally {
        await context.close();
        await browser.close();
    }
})().catch(error => {console.error(error); process.exitCode = 1;});
